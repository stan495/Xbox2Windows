"""Compare native and translated functions of the x87 leaf-function profile: FLD and FSTP with m32, m64
and m80 operands, and FADDP ST(i), ST(0).

Usage:
    python tests/cpu/x87_add.py asm <asm> <def>             regenerate the MASM source and exports
    python tests/cpu/x87_add.py emit <dll> <cpp> [control]   translate (and optionally mutate) the fixture
    python tests/cpu/x87_add.py check <harness> <native> <lifted> [controls...]

Each export runs one sequence from SEQUENCES on an input block at RCX and writes an output block at RDX.
Both the native and the translated export run through x87_call in tests/cpu/x87_harness.asm, which
establishes control word 0x027F and an empty stack and reports the state the export left. The check
compares the output block and 64 guard bytes on each side of the input and output against an
independent Python model that uses exact rational arithmetic.
"""
from fractions import Fraction
import ctypes
import platform
from pathlib import Path
import random
import re
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "tools"))

INPUT, OUTPUT, GUARD = 64, 64, 64

# name: (input kind, sequence). Loads read the input block, stores write the output block.
SEQUENCES = {
    "m32_to_m32": ("f32", [("fld", "m32", 0), ("fstp", "m32", 0)]),
    "m32_to_m64": ("f32", [("fld", "m32", 0), ("fstp", "m64", 0)]),
    "m32_to_m80": ("f32", [("fld", "m32", 0), ("fstp", "m80", 0)]),
    "m64_to_m32": ("f64", [("fld", "m64", 0), ("fstp", "m32", 0)]),
    "m64_to_m64": ("f64", [("fld", "m64", 0), ("fstp", "m64", 0)]),
    "m64_to_m80": ("f64", [("fld", "m64", 0), ("fstp", "m80", 0)]),
    "m80_to_m32": ("m80", [("fld", "m80", 0), ("fstp", "m32", 0)]),
    "m80_to_m64": ("m80", [("fld", "m80", 0), ("fstp", "m64", 0)]),
    "m80_to_m80": ("m80", [("fld", "m80", 0), ("fstp", "m80", 0)]),
    "add_m80": ("pair80", [("fld", "m80", 0), ("fld", "m80", 16), ("faddp", 1), ("fstp", "m80", 0)]),
    "add_to_m64": ("pair80", [("fld", "m80", 0), ("fld", "m80", 16), ("faddp", 1), ("fstp", "m64", 0)]),
    "add_to_m32": ("pair80", [("fld", "m80", 0), ("fld", "m80", 16), ("faddp", 1), ("fstp", "m32", 0)]),
    "add_m64": ("pair64", [("fld", "m64", 0), ("fld", "m64", 8), ("faddp", 1), ("fstp", "m64", 0)]),
    "add_m64_to_m80": ("pair64", [("fld", "m64", 0), ("fld", "m64", 8), ("faddp", 1), ("fstp", "m80", 0)]),
    "add_m32": ("pair32", [("fld", "m32", 0), ("fld", "m32", 4), ("faddp", 1), ("fstp", "m32", 0)]),
    # (a + c) + b through FADDP ST(2), ST(0), with the intermediate sums stored as well.
    "add_three": ("triple80", [("fld", "m80", 0), ("fld", "m80", 16), ("fld", "m80", 32), ("faddp", 2),
                               ("fstp", "m80", 0), ("fld", "m80", 32), ("faddp", 1), ("fstp", "m80", 16)]),
}

PTR = {"m32": "dword", "m64": "qword", "m80": "tbyte"}

# Source mutations of the generated C++ (the helper header is part of it). Each control must mismatch.
ARITH = re.compile(r"x87_arith\{53, 16383, 0x7ffe\}")
CONTROLS = {
    # The sum rounds to 64 significand bits, as with precision control 64.
    "pc64": (ARITH, "x87_arith{64, 16383, 0x7ffe}"),
    # The sum rounds in the binary64 exponent range, as host double arithmetic would.
    "double": (ARITH, "x87_arith{53, 1023, 0x7fe}"),
    # m80 loads go through binary64, as a register model of host doubles would.
    "m80double": (re.compile(r"(x87_from_m80\(uint64_t sig, uint16_t se\) \{ )return \{sig, se\};"),
                  r"\1return x87_from_f64(x87_to_f64({sig, se}, 0x027f));"),
    # Bits shifted out when aligning the smaller addend are dropped instead of kept as a sticky bit.
    "nosticky": (re.compile(r"lo \|= sticky;|lo = \(hi \| lo\) != 0;"),
                 lambda m: ";" if m.group(0).startswith("lo |=") else "lo = 0;"),
    # Of two NaNs of the same kind, the first operand is returned whatever the significands.
    "nanorder": (re.compile(r"\*out = b\.sig > a\.sig \|\| \(b\.sig == a\.sig && !x87_sign\(b\)\) \? b : a;"),
                 "*out = a;"),
    # An exact zero sum of nonzero addends is -0.
    "signedzero": (re.compile(r"return \{0, zero_sign\};  // x \+ \(-x\)"), "return {0, 0x8000};  // x + (-x)"),
}


# ---- MASM generation -------------------------------------------------------------------------------

def asm_line(step):
    op, *args = step
    if op == "faddp":
        return f"    faddp st({args[0]}), st"
    base = "rcx" if op == "fld" else "rdx"
    return f"    {op} {PTR[args[0]]} ptr [{base}+{args[1]}]"


def write_asm(asm_path, def_path):
    lines = ["; Generated by tests/cpu/x87_add.py asm; edit SEQUENCES there and regenerate.",
             "; Source-owned differential fixture for the x87 leaf-function profile. Each export reads an input",
             "; block at RCX, writes an output block at RDX and returns with the x87 stack empty.", ".code", ""]
    for name, (_, steps) in SEQUENCES.items():
        lines += [f"{name} PROC FRAME", "    .endprolog", *(asm_line(s) for s in steps), "    ret", f"{name} ENDP", ""]
    lines.append("END")
    Path(asm_path).write_text("\n".join(lines) + "\n", encoding="ascii")
    Path(def_path).write_text("EXPORTS\n" + "".join(f"    {name}\n" for name in SEQUENCES), encoding="ascii")


# ---- Translation -----------------------------------------------------------------------------------

def emit(image, output, control="lifted"):
    import pefile
    from cpu_leaf_aot import export_rva
    from cpu_ranges import function_ranges
    from ffx_version_query import INTEGER_HEADER, lower, region
    from x87_lower import X87_HEADER

    parts = [INTEGER_HEADER, X87_HEADER]
    with pefile.PE(str(image), fast_load=True) as pe:
        for name in SEQUENCES:
            (bounds,) = function_ranges(pe, export_rva(pe, name))
            code = lower(region(pe, *bounds), ["rcx = a; rdx = b;"], {}, {}, {}, x87=True)
            parts.append(f'extern "C" __declspec(dllexport) word {name}(word a, word b) {{\n{code}\n}}\n')
    text = "".join(parts)
    if control != "lifted":
        expression, replacement = CONTROLS[control]
        text, count = expression.subn(replacement, text)
        if not count:
            raise AssertionError(f"control {control} changed nothing")
        print(f"control {control}: {count} replacements")
    output.write_text(text, encoding="ascii")


# ---- Independent model -----------------------------------------------------------------------------
# Values are raw 80-bit pairs (sig, se). Finite values are classified and converted through Fraction.

INDEFINITE = (0xC000000000000000, 0xFFFF)
J = 1 << 63
Q = 1 << 62
BINARY = {"m32": (24, 127, 8), "m64": (53, 1023, 11)}  # precision, bias, exponent bits


def floor_log2(q):
    e = q.numerator.bit_length() - q.denominator.bit_length()
    if Fraction(2) ** e > q:
        e -= 1
    elif Fraction(2) ** (e + 1) <= q:
        e += 1
    return e


def classify(v):
    sig, se = v
    exp, sign = se & 0x7FFF, se >> 15
    if exp != 0 and not sig & J:
        return ("unsupported",)
    if exp == 0x7FFF:
        return ("inf", sign) if sig == J else ("nan", sign, sig)
    if exp == 0 and sig == 0:
        return ("zero", sign)
    scale = 1 - 16383 - 63 if exp == 0 else exp - 16383 - 63
    return ("finite", sign, Fraction(sig) * Fraction(2) ** scale)


def round_even(q):
    n = q.numerator // q.denominator
    rest = q - n
    return n + (1 if rest > Fraction(1, 2) or (rest == Fraction(1, 2) and n & 1) else 0)


def round_format(q, precision, bias, emax_biased):
    """Round |value| q (nonzero) to nearest-even; returns (m, biased) with m < 2^precision, or None on
    overflow (which rounds to infinity). biased is 0 for a subnormal result."""
    e = floor_log2(q)
    quantum = max(e, 1 - bias) - (precision - 1)
    m = round_even(q / Fraction(2) ** quantum)
    if m == 1 << precision:
        m >>= 1
        quantum += 1
    if m < 1 << (precision - 1):
        return m, 0
    biased = quantum + precision - 1 + bias
    return None if biased > emax_biased else (m, biased)


def m80_exact(sign, q):
    e = floor_log2(q)
    sig = q / Fraction(2) ** (e - 63)
    assert sig.denominator == 1 and J <= sig < 2 * J, q
    return int(sig), (sign << 15) | (e + 16383)


def from_binary(kind, bits):
    precision, bias, exp_bits = BINARY[kind]
    fb = precision - 1
    sign = bits >> (fb + exp_bits)
    exp = (bits >> fb) & ((1 << exp_bits) - 1)
    frac = bits & ((1 << fb) - 1)
    if exp == (1 << exp_bits) - 1:
        return (J, (sign << 15) | 0x7FFF) if frac == 0 else (J | Q | frac << (63 - fb), (sign << 15) | 0x7FFF)
    if exp == 0:
        return (0, sign << 15) if frac == 0 else m80_exact(sign, Fraction(frac) * Fraction(2) ** (1 - bias - fb))
    return m80_exact(sign, (Fraction(frac) / 2 ** fb + 1) * Fraction(2) ** (exp - bias))


def to_binary(kind, v):
    precision, bias, exp_bits = BINARY[kind]
    fb = precision - 1
    all_ones = (1 << exp_bits) - 1
    c = classify(v)
    if c[0] == "unsupported":
        return 1 << (fb + exp_bits) | all_ones << fb | 1 << (fb - 1)
    top = c[1] << (fb + exp_bits)
    if c[0] == "nan":
        return top | all_ones << fb | 1 << (fb - 1) | (c[2] >> (63 - fb)) & ((1 << fb) - 1)
    if c[0] == "inf":
        return top | all_ones << fb
    if c[0] == "zero":
        return top
    rounded = round_format(c[2], precision, bias, all_ones - 1)
    if rounded is None:
        return top | all_ones << fb
    m, biased = rounded
    return top | biased << fb | (m - (1 << fb) if biased else m)


def add(a, b):
    """FADD with control word 0x027F: Intel SDM Vol. 1, Table 4-7 for NaNs; 53-bit rounding with the
    extended exponent range, denormalized at the same bit positions."""
    ca, cb = classify(a), classify(b)
    if "unsupported" in (ca[0], cb[0]):
        return INDEFINITE
    if ca[0] == "nan" or cb[0] == "nan":
        if ca[0] == cb[0] == "nan":
            qa, qb = bool(a[0] & Q), bool(b[0] & Q)
            # Equal significands: the positive NaN, in either operand order (measured).
            pick = (a if qa else b) if qa != qb else (b if (b[0], -(b[1] >> 15)) > (a[0], -(a[1] >> 15)) else a)
        else:
            pick = a if ca[0] == "nan" else b
        return pick[0] | Q, pick[1]
    if ca[0] == "inf" or cb[0] == "inf":
        if ca[0] == cb[0] == "inf" and ca[1] != cb[1]:
            return INDEFINITE
        return a if ca[0] == "inf" else b
    if ca[0] == cb[0] == "zero":
        return 0, 0x8000 if ca[1] and cb[1] else 0
    value = sum((-c[2] if c[1] else c[2]) for c in (ca, cb) if c[0] == "finite")
    if value == 0:
        return 0, 0
    sign = int(value < 0)
    rounded = round_format(abs(value), 53, 16383, 0x7FFE)
    if rounded is None:
        return J, (sign << 15) | 0x7FFF
    m, biased = rounded
    return m << 11, (sign << 15) | biased


def reference(name, data):
    slots, out = [], bytearray(b"\xcc" * OUTPUT)
    for op, *args in SEQUENCES[name][1]:
        if op == "fld":
            kind, offset = args
            raw = int.from_bytes(data[offset:offset + {"m32": 4, "m64": 8, "m80": 10}[kind]], "little")
            slots.append((raw & (2 ** 64 - 1), raw >> 64) if kind == "m80" else from_binary(kind, raw))
        elif op == "fstp":
            kind, offset = args
            v = slots.pop()
            if kind == "m80":
                out[offset:offset + 10] = (v[0] | v[1] << 64).to_bytes(10, "little")
            else:
                size = {"m32": 4, "m64": 8}[kind]
                out[offset:offset + size] = to_binary(kind, v).to_bytes(size, "little")
        else:
            k = len(slots) - 1 - args[0]
            slots[k] = add(slots[k], slots[-1])
            slots.pop()
    assert not slots
    return bytes(out)


# ---- Inputs ----------------------------------------------------------------------------------------

def m80(n, scale=0):
    """The m80 encoding of the nonzero Fraction n * 2^scale, which must fit 64 significand bits."""
    q = Fraction(n) * Fraction(2) ** scale
    return m80_exact(int(q < 0), abs(q))


def special_m80():
    values = [(0, 0), (0, 0x8000), (1, 0), (1, 0x8000), (J - 1, 0), (0x400, 0), (0xC00, 0), (0x401, 0),
              (J, 0), (0xFFFFFFFFFFFFFFFF, 0x8000),                                   # denormals, pseudo-denormals
              (J, 1), (J | 1, 1), (J, 0x3FFF), (J, 0xBFFF), (J | 1, 0x3FFF), (J | 1 << 10, 0x3FFF),
              (J | 3 << 9, 0xBFFF), (0xFFFFFFFFFFFFFFFF, 0x7FFE), (0xFFFFFFFFFFFFF800, 0xFFFE),
              (J, 0x3FFF + 1100), (J | 0x7FF, 0x3FFF - 1100), (J, 0x3FFF + 1023), (J | 1 << 11, 0x3FFF + 1023),
              (J, 0x7FFF), (J, 0xFFFF), INDEFINITE, (J | Q | 5, 0x7FFF), (J | Q | 5, 0xFFFF), (J | 1, 0x7FFF),
              (J | 9, 0xFFFF), (0xFFFFFFFFFFFFFFFF, 0x7FFF),                       # infinities, QNaNs, SNaNs
              (Q, 0x3FFF), (0, 0x7FFF), (Q, 0x7FFF)]                               # unnormal, pseudo-inf/NaN
    return values


def pairs80():
    s = special_m80()
    rows = [(a, b) for a in s for b in s]
    one = (J, 0x3FFF)
    rows += [
        (one, m80(1, -53)), (one, m80(3, -54)), (m80(-1), m80(-1, -53)), (one, m80(1, -64)),  # PC 53 vs 64 halves
        (m80((1 << 53) + 1, -53), m80(1, -54)), (m80(1, -1), m80(1, -54)),
        (m80(3, 1022), m80(3, 1022)), (m80(-3, 1022), m80(-3, 1022)), (m80(1, 1023), m80(1, 1023)),  # past binary64
        (m80(1, -1074), m80(1, -1075)), (m80(1, -1022), m80(-1, -1023)), (m80(1, -1080), m80(1, -1080)),
        ((0xFFFFFFFFFFFFF800, 0x7FFE), (0xFFFFFFFFFFFFF800, 0x7FFE)),               # extended overflow
        ((0xFFFFFFFFFFFFF800, 0x7FFE), (J, 0x7FFE - 53)), ((0xFFFFFFFFFFFFF800, 0x7FFE), (J, 0x7FFE - 54)),
        ((J - 1, 0), (1, 0)), ((J, 1), (1, 0x8000)), ((J | 0x800, 1), (J, 0x8001)),          # extended underflow
        ((0x1234, 0), (0x5678, 0)), ((J, 1), (J | 0x400, 0x8001)), ((0xFFF, 0), (0, 0)),
        ((J | 1 << 10, 0x3FFF), m80(1, -200)), ((J | 3 << 10, 0x3FFF), m80(-1, -200)),  # a half plus a tail
        ((J | 1 << 10, 0x3FFF), (1, 0)), ((J | 3 << 10, 0xBFFF), (1, 0)),
        ((J | 5, 0x7FFF), (J | 5, 0xFFFF)), ((J | 5, 0xFFFF), (J | 5, 0x7FFF)),          # NaN ties by sign
        ((J | Q | 5, 0xFFFF), (J | 5, 0x7FFF)), ((J | 5, 0x7FFF), (J | Q | 5, 0xFFFF)),
        (m80((1 << 63) + 1, -63), m80(-1)), (one, m80(-1, -200)), (one, m80(1, -200)), (m80(-1), m80(1, -200)),
    ]
    rng = random.Random(87)
    for _ in range(700):
        exp = rng.randint(0x3FFF - 70, 0x3FFF + 70)
        a = (J | rng.getrandbits(63), exp | rng.choice((0, 0x8000)))
        b = (J | rng.getrandbits(63), (exp + rng.randint(-66, 66)) | rng.choice((0, 0x8000)))
        rows.append((a, b))
    return rows


def f64_bits():
    bits = [0, 1 << 63, 1, 0x000FFFFFFFFFFFFF, 0x0010000000000000, 0x7FEFFFFFFFFFFFFF, 0x7FF0000000000000,
            0xFFF0000000000000, 0x7FF8000000000000, 0xFFF8000000000000, 0x7FF0000000000001, 0x7FF4000000000000,
            0xFFF0000000000123, 0x3FF0000000000000, 0xBFF0000000000001, 0x3CA0000000000000, 0x3CA0000000000001,
            0x8000000000000001]
    rng = random.Random(64)
    return bits + [rng.getrandbits(64) for _ in range(30)]


def f32_bits():
    bits = [0, 0x80000000, 1, 0x007FFFFF, 0x00800000, 0x7F7FFFFF, 0x7F800000, 0xFF800000, 0x7FC00000, 0xFFC00000,
            0x7F800001, 0x7FA00000, 0xFF801234, 0x3F800000, 0xBF800001, 0x33800000, 0x33800001]
    rng = random.Random(32)
    return bits + [rng.getrandbits(32) for _ in range(30)]


def m80_singles():
    rows = special_m80()
    for exp in (0x3FFF - 1022, 0x3FFF - 1023, 0x3FFF - 1074, 0x3FFF - 1075, 0x3FFF + 1023, 0x3FFF + 1024,
                0x3FFF - 126, 0x3FFF - 149, 0x3FFF - 150, 0x3FFF + 127, 0x3FFF + 128):
        for sig in (J, J | 1, J | 0x3FF, J | 0x400, J | 0x7FF, J | 0x800, 0xFFFFFFFFFFFFF800, 0xFFFFFFFFFFFFFFFF,
                    J | 0xFFFFFFFFFF, J | 0x8000000000, 0xFFFFFF0000000000, 0xFFFFFF8000000000):
            rows += [(sig, exp), (sig, exp | 0x8000)]
    return rows


def m80_bytes(v):
    return v[0].to_bytes(8, "little") + v[1].to_bytes(2, "little") + b"\0" * 6


def cases():
    f64, f32 = f64_bits(), f32_bits()
    rng = random.Random(3)
    blocks = {
        "f32": [b.to_bytes(4, "little") for b in f32],
        "f64": [b.to_bytes(8, "little") for b in f64],
        "m80": [m80_bytes(v) for v in m80_singles()],
        "pair80": [m80_bytes(a) + m80_bytes(b) for a, b in pairs80()],
        "pair64": [a.to_bytes(8, "little") + b.to_bytes(8, "little") for a in f64[:18] for b in f64[:18]]
                  + [(0x3FF0000000000000).to_bytes(8, "little") + (0x3CA0000000000001).to_bytes(8, "little")],
        "pair32": [a.to_bytes(4, "little") + b.to_bytes(4, "little") for a in f32[:17] for b in f32[:17]],
        "triple80": [b"".join(m80_bytes(v) for v in rng.sample(special_m80(), 3)) for _ in range(300)],
    }
    for name, (kind, _) in SEQUENCES.items():
        for block in blocks[kind]:
            yield name, block.ljust(INPUT, b"\0")


# ---- Check -----------------------------------------------------------------------------------------

class Runner:
    """Calls an export through the native harness with guarded input and output buffers."""

    def __init__(self, harness_path, path):
        self.harness = ctypes.CDLL(str(Path(harness_path).resolve()))
        self.call = self.harness.x87_call
        self.call.argtypes, self.call.restype = [ctypes.c_void_p, ctypes.c_void_p, ctypes.c_void_p], ctypes.c_uint64
        self.seeded = self.harness.x87_seeded
        self.seeded.argtypes, self.seeded.restype = [ctypes.c_void_p] * 4, ctypes.c_uint64
        self.lib = ctypes.CDLL(str(Path(path).resolve()))
        self.path = Path(path).resolve()

    def export(self, name):
        """The fixture export `name`, or a message that names the stale DLL."""
        try:
            return getattr(self.lib, name)
        except AttributeError:
            # A partial build leaves the variants at their previous revision, so the newest
            # export can be missing from one of them. Say which file and what to rebuild.
            raise AssertionError(
                f"{self.path.name} has no export {name!r}: this fixture DLL predates the export. "
                f"Rebuild the target that produces {self.path.name} before running this check."
            ) from None

    def _buffers(self, data):
        guard = b"\xa5" * GUARD
        source = (ctypes.c_uint8 * (INPUT + 2 * GUARD)).from_buffer_copy(guard + data + guard)
        target = (ctypes.c_uint8 * (OUTPUT + 2 * GUARD)).from_buffer_copy(guard + b"\xcc" * OUTPUT + guard)
        return guard, source, target

    def _output(self, name, data, guard, source, target):
        if bytes(source) != guard + data + guard or bytes(target[:GUARD]) + bytes(target[-GUARD:]) != guard * 2:
            raise AssertionError(f"{name} wrote outside its output block")
        return bytes(target[GUARD:GUARD + OUTPUT])

    def __call__(self, name, data):
        guard, source, target = self._buffers(data)
        function = ctypes.cast(self.export(name), ctypes.c_void_p).value
        state = self.call(function, ctypes.addressof(source) + GUARD, ctypes.addressof(target) + GUARD)
        return self._output(name, data, guard, source, target), state

    def with_live_value(self, harness, name, data):
        """Run name through the harness export `harness` from x87_seeded, which enters it with SEED_VALUE
        in ST(0) and SEED_CONTROL loaded. Returns the output block, the harness state, the value popped
        afterwards (10 bytes) and the 28-byte environment seen before that pop."""
        guard, source, target = self._buffers(data)
        probe = (ctypes.c_uint8 * 80).from_buffer_copy(
            m80_bytes(SEED_VALUE)[:10] + b"\0" * 6 + SEED_CONTROL.to_bytes(2, "little") + b"\0" * 62)
        io = (ctypes.c_uint64 * 2)(ctypes.addressof(source) + GUARD, ctypes.addressof(target) + GUARD)
        state = self.seeded(ctypes.cast(getattr(self.harness, harness), ctypes.c_void_p).value,
                            ctypes.cast(getattr(self.lib, name), ctypes.c_void_p).value,
                            ctypes.addressof(io), ctypes.addressof(probe))
        return self._output(name, data, guard, source, target), state, bytes(probe[32:42]), bytes(probe[48:76])


# A caller value the harness must preserve: pi with all 64 significand bits, under a control word that
# differs from the profile's in precision and rounding (64 bits, toward zero).
SEED_VALUE = (0xC90FDAA22168C235, 0x4000)
SEED_CONTROL = 0x0F7F


def entry_state_ok(state):
    return (state & 0xFFFF, (state >> 32) & 0xFFFF, (state >> 16) & 0x3800) == (0x027F, 0xFFFF, 0)


def preserved(run, harness, name, data, want):
    """Whether a run with a live caller value gave the expected output from the profile's entry state
    and returned the caller's value bytes, control word, TOP 7 and the single valid tag."""
    got, state, value, env = run.with_live_value(harness, name, data)
    control, status, tags = (int.from_bytes(env[k:k + 2], "little") for k in (0, 4, 8))
    return (got == want and entry_state_ok(state) and value == m80_bytes(SEED_VALUE)[:10]
            and (control, (status >> 11) & 7, tags) == (SEED_CONTROL, 7, 0x3FFF))


def check(harness_path, native_path, lifted_path, *control_paths):
    expected = [(name, data, reference(name, data)) for name, data in cases()]
    for label, path in (("native", native_path), ("lifted", lifted_path)):
        run = Runner(harness_path, path)
        bad = 0
        for name, data, want in expected:
            got, state = run(name, data)
            control, status, tags = state & 0xFFFF, (state >> 16) & 0xFFFF, (state >> 32) & 0xFFFF
            if (control, tags, status & 0x3800) != (0x027F, 0xFFFF, 0):
                raise AssertionError(f"{label} {name} left control {control:#06x}, status {status:#06x}, "
                                     f"tags {tags:#06x}; the profile requires an empty stack at TOP 0")
            if got != want:
                if not bad:
                    print(f"{label} first mismatch: {name}(input {data[:48].hex()})\n  got      {got[:16].hex()}\n"
                          f"  expected {want[:16].hex()}")
                bad += 1
        if bad:
            raise AssertionError(f"{label}: {bad}/{len(expected)} mismatches")
    print(f"{len(expected)} cases over {len(SEQUENCES)} exports (output block and guards) matched the reference "
          "in native and translated DLLs; each export returned with control 0x027f and an empty stack")
    print(f"processor: {platform.processor()}")
    # The harness itself: a caller value in the register each export reuses must survive the call.
    first = {}
    for name, data, want in expected:
        first.setdefault(name, (data, want))
    for label, path in (("native", native_path), ("lifted", lifted_path)):
        run = Runner(harness_path, path)
        failed = [name for name, (data, want) in first.items() if not preserved(run, "x87_call", name, data, want)]
        if failed:
            raise AssertionError(f"x87_call lost a live caller value or control word around {label} {failed}")
    envonly = sum(1 for name, (data, want) in first.items()
                  if not preserved(Runner(harness_path, native_path), "x87_call_envonly", name, data, want))
    print(f"x87_call kept a live caller ST(0) value and control word {SEED_CONTROL:#06x} around all "
          f"{len(first)} native and translated exports; control envonly (FNSTENV/FLDENV): "
          f"{envonly}/{len(first)} lost it")
    if envonly != len(first):
        raise AssertionError("control envonly preserved the caller value")
    for path in control_paths:
        control = Path(path).stem.rsplit("_", 1)[-1]
        run = Runner(harness_path, path)
        bad = sum(1 for name, data, want in expected if run(name, data)[0] != want)
        print(f"control {control}: {bad}/{len(expected)} mismatches")
        if not bad:
            raise AssertionError(f"control {control} matched every case")
    check_rejections()


def check_rejections():
    from iced_x86 import Decoder
    from ffx_version_query import lower

    def attempt(hex_bytes, *, x87=True, calls=None, exits=None):
        body = list(Decoder(64, bytes.fromhex(hex_bytes), ip=0x1000))
        try:
            lower(body, [], {}, calls or {}, exits or {}, x87=x87)
        except ValueError as exc:
            return str(exc)
        return None

    fld, fstp = "d9 01", "dd 19"  # fld dword ptr [rcx]; fstp qword ptr [rdx]
    rejected = {
        "the profile off (default)": (attempt(f"{fld} {fstp} c3", x87=False), "unsupported query operation"),
        "fbld m80": (attempt(f"{fld} df 21 de c1 {fstp} c3"), "unsupported x87 operation"),
        "fsin": (attempt(f"{fld} d9 fe {fstp} c3"), "unsupported x87 operation"),
        "fnstsw m16": (attempt(f"{fld} dd 3a {fstp} c3"), "stores status-word bits"),
        "fldcw": (attempt(f"d9 29 {fld} {fstp} c3"), "fldcw"),
        "fninit": (attempt(f"{fld} db e3 {fstp} c3"), "unsupported x87 operation"),
        "ffree st(0)": (attempt(f"{fld} dd c0 {fstp} c3"), "frees an occupied register"),
        "a ninth push": (attempt(f"{fld} " * 9 + f"{fstp} " * 9 + "c3"), "x87 stack overflow"),
        "fstp on an empty stack": (attempt(f"{fstp} c3"), "x87 stack underflow"),
        "faddp with one value": (attempt(f"{fld} de c1 {fstp} c3"), "x87 stack underflow"),
        "faddp st(0), st": (attempt(f"{fld} {fld} de c0 {fstp} {fstp} c3"), "unsupported x87 operation"),
        "a return with a value": (attempt(f"{fld} c3"), "x87 stack not empty at return"),
        "depths that differ at a join": (attempt(f"{fld} 74 02 {fld} {fstp} c3"), "meet at"),
        "a call with a live value": (attempt(f"{fld} e8 00 00 00 00 {fstp} c3", calls={0x1002: ";"}), "across the call"),
        "an external edge with a live value": (attempt(f"{fld} e9 00 01 00 00", exits={0x1107: "return 0;"}),
                                               "external edge"),
        "an indirect jump with a live value": (attempt(f"{fld} ff e0"), "indirect branch"),
        "an unreachable fld": (attempt(f"c3 {fld} {fstp} c3"), "unknown x87 stack depth"),
    }
    for case, (message, needle) in rejected.items():
        if message is None or needle not in message:
            raise AssertionError(f"{case}: expected a rejection containing {needle!r}, got {message!r}")
    print(f"rejected {len(rejected)} sequences outside the profile, including: " + "; ".join(rejected))


